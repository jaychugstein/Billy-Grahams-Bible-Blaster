# Daytime street background, drawn black-on-white, stored inverted for the game (which flips the screen).
from PIL import Image, ImageDraw
import random
random.seed(7)
W,H=128,64; HZ=21
im=Image.new('1',(W,H),1); d=ImageDraw.Draw(im)
K=0  # ink
def house(x,w,h,roof='gable',door=True,chimney=False):
    y=HZ-h
    d.rectangle((x,y,x+w,HZ),outline=K,fill=1)
    if roof=='gable':
        d.polygon([(x-1,y),(x+w//2,y-5),(x+w+1,y)],outline=K,fill=1)
        for i in range(1,4): d.line((x+w//2-i*2,y-5+i*1+1,x+w//2+i*2,y-5+i*1+1),fill=K) if False else None
    else:  # flat roof with overhang
        d.line((x-1,y,x+w+1,y),fill=K); d.line((x-1,y-1,x+w+1,y-1),fill=K)
    if chimney: d.rectangle((x+w-4,y-6,x+w-2,y-2),outline=K,fill=1)
    # windows
    for wx in range(x+2,x+w-2,5):
        if door and abs(wx-(x+w//2))<3: continue
        d.rectangle((wx,y+2,wx+2,y+4),outline=K)
    if door: d.rectangle((x+w//2-1,HZ-4,x+w//2+1,HZ),outline=K)
def tree(x,r=4,tall=4):
    d.line((x,HZ-tall,x,HZ),fill=K)
    cy=HZ-tall-r
    d.ellipse((x-r,cy-r,x+r,cy+r),outline=K,fill=1)
    for _ in range(r*3):
        a=random.uniform(-r+1,r-1); b=random.uniform(-r+1,r-1)
        if a*a+b*b<(r-1.5)**2: im.putpixel((int(x+a),int(cy+b)),K)
def bush(x,w):
    d.ellipse((x,HZ-4,x+w,HZ+1),outline=K,fill=1)
# skyline left
house(3,12,7,'gable',chimney=True); tree(19,3,3); house(24,9,5,'flat'); bush(34,6)
# skyline right
bush(86,6); house(94,10,6,'flat'); tree(108,3,3); house(113,12,8,'gable',chimney=True)
# far houses near the vanishing point
house(42,6,3,'gable',door=False); house(78,6,3,'gable',door=False)
# horizon
d.line((0,HZ,127,HZ),fill=K)
# road edges and sidewalks running to the vanishing point
VX=64
d.line((59,HZ,6,63),fill=K); d.line((69,HZ,122,63),fill=K)
d.line((56,HZ,-14,63),fill=K); d.line((72,HZ,142,63),fill=K)
# curb tick marks on the sidewalks (perspective joints)
for t in (0.18,0.34,0.52,0.74):
    y=int(HZ+(63-HZ)*t)
    xl1=59+(6-59)*t; xl2=56+(-14-56)*t; xr1=69+(122-69)*t; xr2=72+(142-72)*t
    d.line((xl2,y,xl1,y),fill=K); d.line((xr1,y,xr2,y),fill=K)
# grass: sparse stipple outside the sidewalks
for y in range(HZ+1,64):
    t=(y-HZ)/(63-HZ)
    xl=56+(-14-56)*t; xr=72+(142-72)*t
    for x in range(0,128):
        if (x<xl-1 or x>xr+1):
            n=1 if y<32 else 2
            if random.random()< (0.025+0.045*t): im.putpixel((x,y),K)
# centre dashes
y=HZ+2
while y<64:
    t=(y-HZ)/(63-HZ); L=1+int(t*5)
    d.line((VX,y,VX,min(63,y+L)),fill=K); y+=L+2+int(t*4)
# lamp posts on the sidewalks
def lamp(x,foot,top,dirn):
    d.line((x,top,x,foot),fill=K); d.line((x-1,foot,x+1,foot),fill=K)
    d.line((x,top,x+4*dirn,top-1),fill=K); d.line((x+4*dirn,top-1,x+6*dirn,top),fill=K)
    d.rectangle((min(x+5*dirn,x+7*dirn),top+1,max(x+5*dirn,x+7*dirn),top+2),fill=K)
lamp(24,40,6,1); lamp(104,40,6,-1)
# sun
d.ellipse((80,3,88,11),outline=K,fill=1)
for dx,dy in ((0,-6),(0,6),(-6,0),(6,0),(-4,-4),(4,-4),(-4,4),(4,4)):
    im.putpixel((84+dx,7+dy),K)
im.save('bg.png')
im.convert('L').resize((512,256),Image.NEAREST).save('bg_x4.png')
# store inverted (game flips the whole screen to daytime)
data=[]
for p in range(8):
    for x in range(W):
        b=0
        for r in range(8):
            if im.getpixel((x,p*8+r))==K: b|=1<<r
        data.append(b)
with open('../BibleBlaster/bg.h','w') as f:
    f.write('// generated by art/make_bg.py: the daytime street, stored as ink bits (screen gets flipped)\n#pragma once\nconst uint8_t BG[1024] PROGMEM = {\n')
    for i in range(0,1024,32): f.write(','.join(map(str,data[i:i+32]))+',\n')
    f.write('};\n')

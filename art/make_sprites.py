from sprites import *
sizes=[M,N,B]; types=['cave','suit','unit','bahai']
out=['// generated by art/make_sprites.py','#pragma once',
     '// walker sprites: [size far/mid/near][type cave/suit/unit/bahai][frame] rows of (white, mask)',
     '// bit 0 = leftmost column. Mask includes a 1 pixel black outline.']
offs=[];data=[];dims=[]
for S in sizes:
    W=S['W']+2
    for t in types:
        for f in range(2):
            R=build(S,t,f); H=len(R)+2
            wh=[0]*H; sol=[[0]*W for _ in range(H)]
            for y,r in enumerate(R):
                for x,c in enumerate(r):
                    if c=='X': wh[y+1]|=1<<(x+1)
                    if c!='.': sol[y+1][x+1]=1
            mk=[0]*H
            for y in range(H):
                for x in range(W):
                    if any(0<=y+dy<H and 0<=x+dx<W and sol[y+dy][x+dx] for dx,dy in((0,0),(1,0),(-1,0),(0,1),(0,-1))): mk[y]|=1<<x
            offs.append(len(data))
            for y in range(H): data+= [wh[y],mk[y]]
    dims.append((W,H))
out.append('const uint8_t SPR_W[3] = {%s};'%','.join(str(d[0]) for d in dims))
out.append('const uint8_t SPR_H[3] = {%s};'%','.join(str(d[1]) for d in dims))
out.append('const uint16_t SPR_OFF[24] PROGMEM = {%s};'%','.join(map(str,offs)))
out.append('const uint32_t SPR[%d] PROGMEM = {'%len(data))
for i in range(0,len(data),8): out.append('  '+','.join('0x%X'%v for v in data[i:i+8])+',')
out.append('};')
open('../BibleBlaster/sprites.h','w').write('\n'.join(out)+'\n')
print(dims,len(data)*4,'bytes')


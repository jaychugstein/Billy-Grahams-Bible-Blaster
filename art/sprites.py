# walker types: (head, body, legs, club?, bible?)
TYPES = {
 'cave': ('cave','cave','cave',True,False),
 'suit': ('neat','suit','suit',False,True),
 'unit': ('cave','unit','cave',False,False),
 'bahai':('robe','robe','robe',False,False),
}
def rows(s): return [r for r in s.strip('\n').split('\n')]
def build(S, t, f):
    h,b,l,club,bib=TYPES[t]
    R = rows(S['head'][h]) + rows(S['body'][b]) + rows(S['legs'][l][f])
    R = [list(r.ljust(S['W'],'.')[:S['W']]) for r in R]
    def over(part, y0=0):
        for y,r in enumerate(rows(part)):
            for x,c in enumerate(r):
                if c!='.' and y0+y < len(R): R[y0+y][x]=c
    if club: over(S['club'], len(rows(S['head'][h]))-4)
    if bib: over(S['bible'], len(rows(S['head'][h])))
    return [''.join(r) for r in R]


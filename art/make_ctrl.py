# Controls screen: a small Arduboy with its buttons labelled (white on black)
from PIL import Image, ImageDraw
import sys
sys.path.insert(0, __import__('os').path.dirname(__import__('os').path.abspath(__file__)))
from font5x7 import FONT
def text(im,s,x,y):
    for ch in s:
        g=FONT[ord(ch)*5:ord(ch)*5+5]
        for cx in range(5):
            for cy in range(7):
                if g[cx]>>cy&1: im.putpixel((x+cx,y+cy),1)
        x+=6
im=Image.new('1',(128,64),0); d=ImageDraw.Draw(im)
X0,Y0,X1,Y1=34,1,86,53
d.rounded_rectangle((X0,Y0,X1,Y1),radius=5,outline=1)
d.rounded_rectangle((X0+2,Y0+2,X1-2,Y1-2),radius=4,outline=1)
# screen with a tiny bible and cross on it
sx0,sy0,sx1,sy1=X0+8,Y0+5,X1-8,Y0+25
d.rectangle((sx0,sy0,sx1,sy1),outline=1)
bx,by=(sx0+sx1)//2,(sy0+sy1)//2
d.rectangle((bx-6,by-6,bx+6,by+7),fill=1)
d.line((bx,by-4,bx,by+4),fill=0); d.line((bx-2,by-2,bx+2,by-2),fill=0)
# d-pad
cx,cy=X0+13,Y0+38
d.rectangle((cx-2,cy-7,cx+2,cy+7),fill=1); d.rectangle((cx-7,cy-2,cx+7,cy+2),fill=1); d.point((cx,cy),0)
# buttons: inner (lower left) and outer (upper right)
ix,iy=X1-19,Y0+42; ox,oy=X1-10,Y0+36
d.ellipse((ix-4,iy-4,ix+4,iy+4),outline=1)
d.ellipse((ox-4,oy-4,ox+4,oy+4),outline=1)
# labels + leader lines
text(im,'AIM',2,30); d.line((20,33,cx-8,33),1)
# little left/right and up/down arrows under the AIM label
d.polygon([(2,44),(5,41),(5,47)],fill=1); d.polygon([(12,44),(9,41),(9,47)],fill=1)
d.polygon([(19,40),(16,43),(22,43)],fill=1); d.polygon([(19,48),(16,45),(22,45)],fill=1)
text(im,'FIRE',99,22); d.line((110,30,110,oy),1); d.line((110,oy,ox+5,oy),1)
text(im,'RELOAD',91,46); d.line((ix,iy+5,ix,iy+7),1); d.line((ix,iy+7,90,iy+7),1); d.line((90,iy+7,90,49),1)
im.save('ctrl.png'); im.convert('L').resize((512,256),Image.NEAREST).save('ctrl_x4.png')
OX,OY,OR=ox,oy,4
data=[]
for p in range(8):
    for x in range(128):
        b=0
        for r in range(8):
            if im.getpixel((x,p*8+r)): b|=1<<r
        data.append(b)
with open('../BibleBlaster/ctrl.h','w') as f:
    f.write('// generated by art/make_ctrl.py: controls screen\n#pragma once\n')
    f.write(f'#define CTRL_FIRE_X {OX}\n#define CTRL_FIRE_Y {OY}\n')
    f.write('const uint8_t CTRL[1024] PROGMEM = {\n')
    for i in range(0,1024,32): f.write(','.join(map(str,data[i:i+32]))+',\n')
    f.write('};\n')
